function delay(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

// Переводит "сырую" запись 1С (с Вариант1..4, НомерПравильногоОтвета)
// в удобный для компонента вид (options[], correctIndex).
// Именно эту функцию нужно будет свериться/подправить, когда
// придут реальные данные — вся остальная логика её не касается.
function mapODataTask(raw) {
  return {
    id: raw.Ref_Key,
    question: raw.ТекстВопроса,
    options: [raw.Вариант1, raw.Вариант2, raw.Вариант3, raw.Вариант4],
    correctIndex: raw.НомерПравильногоОтвета - 1, // в 1С считаем с 1, в JS — с 0
    explanation: raw.Пояснение,
  };
}

export async function fetchTasks() {
  if (USE_MOCK) {
    await delay(500);
    return mockTasks.map(mapODataTask);
  }

  let response;
  try {
    response = await fetch(`${TASKS_ENDPOINT}?$format=json`, {
      headers: { Accept: "application/json" },
      // TODO: уточнить способ авторизации (Basic Auth / cookie) у команды
    });
  } catch {
    throw new Error("Не удалось связаться с сервером. Проверьте соединение.");
  }

  if (!response.ok) {
    throw new Error(`Сервер вернул ошибку (${response.status}).`);
  }

  const data = await response.json();
  return data.value.map(mapODataTask);
}

export async function submitAnswer(taskId, answerIndex) {
  if (USE_MOCK) {
    await delay(400);
    const raw = mockTasks.find((t) => t.Ref_Key === taskId);
    if (!raw) throw new Error("Задание не найдено.");
    const task = mapODataTask(raw);
    return { correct: answerIndex === task.correctIndex, explanation: task.explanation };
  }

  let response;
  try {
    response = await fetch(RESULTS_ENDPOINT, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        Задача_Key: taskId,
        ВыбранныйОтвет: answerIndex + 1, // обратно в нумерацию 1С (с 1)
      }),
    });
  } catch {
    throw new Error("Не удалось отправить ответ. Проверьте соединение.");
  }

  if (!response.ok) {
    throw new Error(`Сервер не принял ответ (${response.status}).`);
  }

  return response.json();
}
